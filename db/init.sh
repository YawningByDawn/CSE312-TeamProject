#!/bin/sh
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<EOF
CREATE USER auth WITH PASSWORD '$AUTH_DB_PASSWORD';
CREATE DATABASE auth OWNER auth;
REVOKE CONNECT ON DATABASE auth FROM PUBLIC;
CREATE USER app WITH PASSWORD '$APP_DB_PASSWORD';
CREATE DATABASE app OWNER app;
REVOKE CONNECT ON DATABASE app FROM PUBLIC;
EOF
